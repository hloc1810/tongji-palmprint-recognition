"""ResNet18 architecture and ROI dataset transformations."""
from __future__ import annotations
import random
from pathlib import Path
import numpy as np
import pandas as pd
from PIL import Image
from ..data.dataset import read_gray, resolve_path
from ..utils import hash_file

def torch_modules():
    try:
        import torch
        from torch import nn
        from torch.utils.data import DataLoader, Dataset
        from torchvision import models, transforms
    except ImportError as exc:
        raise RuntimeError("Install CNN extras: pip install -e '.[cnn]'") from exc
    return torch, nn, DataLoader, Dataset, models, transforms


def set_seed(seed: int) -> None:
    torch, *_ = torch_modules()
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False


def preprocessing(training: bool, size: int = 224):
    *_, transforms = torch_modules()
    ops = [transforms.Grayscale(num_output_channels=3),
           transforms.Resize((size, size), interpolation=transforms.InterpolationMode.BILINEAR)]
    if training:
        ops.extend([transforms.RandomRotation(5,
                          interpolation=transforms.InterpolationMode.BILINEAR, fill=128),
                    transforms.ColorJitter(brightness=0.08, contrast=0.08)])
    ops.extend([transforms.ToTensor(),
                transforms.Normalize(mean=(0.485, 0.456, 0.406),
                                     std=(0.229, 0.224, 0.225))])
    return transforms.Compose(ops)


class PalmROIDataset:
    """Top-level map-style dataset so DataLoader workers work on Windows/spawn."""

    def __init__(self, frame: pd.DataFrame, root: Path, train: bool, size: int):
        self.rows = frame.reset_index(drop=True)
        self.root = Path(root)
        self.transform = preprocessing(train, size)
        # A manifest generated by `prepare` includes hashes for every audited ROI.
        # Verify at loader construction, not every training epoch.
        if "sha256" in self.rows:
            for row in self.rows.itertuples(index=False):
                path = resolve_path(self.root, row.path)
                if hash_file(path) != row.sha256:
                    raise RuntimeError(f"ROI changed after dataset audit: {row.sample_uid}")

    def __len__(self):
        return len(self.rows)

    def __getitem__(self, idx):
        import torch
        row = self.rows.iloc[idx]
        gray = read_gray(resolve_path(self.root, row.path))
        picture = self.transform(Image.fromarray(gray))
        return picture, torch.tensor(int(row.palm_id) - 1, dtype=torch.long)


def make_dataset(frame: pd.DataFrame, root: Path, train: bool, size: int = 224):
    return PalmROIDataset(frame, root, train, size)


def make_resnet(classes: int, weights: str):
    _, nn, _, _, models, _ = torch_modules()
    if weights not in ("none", "imagenet1k_v1"):
        raise ValueError("weights must be none or imagenet1k_v1")
    w = models.ResNet18_Weights.IMAGENET1K_V1 if weights != "none" else None
    model = models.resnet18(weights=w)
    model.fc = nn.Linear(model.fc.in_features, classes)
    return model


def set_trainable(model, *, layer4: bool) -> None:
    for parameter in model.parameters():
        parameter.requires_grad = False
    for parameter in model.fc.parameters():
        parameter.requires_grad = True
    if layer4:
        for parameter in model.layer4.parameters():
            parameter.requires_grad = True
